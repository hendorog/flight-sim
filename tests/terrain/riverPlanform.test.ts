// The baked river planform (src/world/terrain/riverPlanform.ts) is what meander.ts grows from hydrology.ts's valley
// axis and reach table today. FS_RIVER_BAKE=1 writes it afresh after a deliberate change to either.
import { describe, expect, it } from 'vitest';
import { meanderSetup } from '../../src/world/terrain/hydrology';
import { encodePolyline, growMeanders } from '../../src/world/terrain/meander';
import { RIVER_PLANFORM } from '../../src/world/terrain/riverPlanform';

// node:fs without the node type package (tests are type-checked with the DOM library only), as tests/golden has it.
const fs = (await import(/* @vite-ignore */ 'node:fs' as string)) as { writeFileSync(path: URL, data: string): void };
const BAKE = (globalThis as unknown as { process: { env: Record<string, string | undefined> } }).process.env.FS_RIVER_BAKE;

describe('river planform bake', () => {
  it('matches a fresh meander growth', () => {
    const { axis, reach, seed, ds, steps } = meanderSetup();
    const grown = growMeanders(axis, reach, seed, ds, steps);
    const fresh = {
      channel: encodePolyline(grown.north, grown.east),
      oxbows: grown.oxbows.map((o) => ({ line: encodePolyline(o.north, o.east), age: Math.round(o.age * 1000) / 1000 })),
    };
    if (BAKE) {
      const src = new URL('../../src/world/terrain/riverPlanform.ts', import.meta.url);
      const head = '// GENERATED by tests/terrain/riverPlanform.test.ts (FS_RIVER_BAKE=1): the river channel grown into meanders by\n' +
        "// meander.ts from hydrology.ts's valley axis and reach table, and the oxbow lakes it left. Do not edit by hand.\n";
      fs.writeFileSync(src, head + 'export const RIVER_PLANFORM: { channel: string; oxbows: ReadonlyArray<{ line: string; age: number }> } = ' +
        JSON.stringify(fresh, null, 1) + ';\n');
      return;
    }
    expect(RIVER_PLANFORM.channel).toBe(fresh.channel);
    expect(RIVER_PLANFORM.oxbows).toEqual(fresh.oxbows);
  }, 120_000);
});
