// The baked road network (src/world/terrain/roadNetwork.ts) is what roadPlanner.ts plans over today's terrain.
// FS_ROAD_BAKE=1 writes it afresh after a deliberate change to the planner or to the terrain under it.
import { describe, expect, it } from 'vitest';
import { planRoadNetwork } from '../../src/world/terrain/roadPlanner';
import { ROAD_NETWORK } from '../../src/world/terrain/roadNetwork';

// node:fs without the node type package (tests are type-checked with the DOM library only), as tests/golden has it.
const fs = (await import(/* @vite-ignore */ 'node:fs' as string)) as { writeFileSync(path: URL, data: string): void };
const BAKE = (globalThis as unknown as { process: { env: Record<string, string | undefined> } }).process.env.FS_ROAD_BAKE;

describe('road network bake', () => {
  it('matches a fresh plan', () => {
    const fresh = planRoadNetwork();
    if (BAKE) {
      const src = new URL('../../src/world/terrain/roadNetwork.ts', import.meta.url);
      const head =
        '// GENERATED by tests/terrain/roadNetwork.test.ts (FS_ROAD_BAKE=1): the regional road network roadPlanner.ts plans\n' +
        '// over today\'s terrain (villages, roads, river crossings). Do not edit by hand.\n';
      fs.writeFileSync(
        src,
        head +
          'export const ROAD_NETWORK: { villages: ReadonlyArray<{ north: number; east: number; radius: number }>; roads: ReadonlyArray<{ kind: number; line: string }>; crossings: ReadonlyArray<{ north: number; east: number; bearing: number }> } = ' +
          JSON.stringify(fresh, null, 1) +
          ';\n',
      );
      return;
    }
    expect(ROAD_NETWORK).toEqual(fresh);
  }, 300_000);
});
